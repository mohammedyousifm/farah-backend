<?php

namespace App\Filament\Resources\Settlements;

use App\Enums\SettlementStatus;
use App\Filament\Concerns\ModuleResource;
use App\Filament\NavGroup;
use App\Filament\Resources\Settlements\Pages\ListSettlements;
use App\Filament\Resources\Settlements\Pages\ViewSettlement;
use App\Filament\Resources\Settlements\RelationManagers\EntriesRelationManager;
use App\Filament\Support\Fmt;
use App\Models\Settlement;
use App\Services\KpiService;
use Filament\Actions\ViewAction;
use Filament\Forms\Components\DatePicker;
use Filament\Infolists\Components\TextEntry;
use Filament\Resources\Resource;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Tables\Columns\Summarizers\Sum;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\Filter;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;

/**
 * Settlement cycle: statements are generated by SettlementService, then
 * approved / rejected / marked paid from the view page. Never edited by hand.
 */
class SettlementResource extends Resource
{
    use ModuleResource;

    protected static ?string $model = Settlement::class;

    protected static string $permissionModule = 'settlements';

    protected static string $langKey = 'settlements';

    protected static string|\UnitEnum|null $navigationGroup = NavGroup::Finance;

    protected static string|\BackedEnum|null $navigationIcon = 'heroicon-o-building-library';

    protected static ?int $navigationSort = 50;

    protected static ?string $recordTitleAttribute = 'number';

    public static function readOnly(): bool
    {
        return true;
    }

    public static function getNavigationBadge(): ?string
    {
        $count = app(KpiService::class)->queue()['settlements'];

        return $count ? (string) $count : null;
    }

    public static function getNavigationBadgeColor(): ?string
    {
        return 'warning';
    }

    public static function infolist(Schema $schema): Schema
    {
        $money = fn ($state) => Fmt::sar($state);

        return $schema->components([
            Section::make()->columnSpanFull()->columns(4)->schema([
                TextEntry::make('number')->label(__('admin.fields.number'))->weight('bold')->copyable(),
                TextEntry::make('provider.name_ar')->formatStateUsing(Fmt::localized('provider.name'))->label(__('admin.fields.provider')),
                TextEntry::make('status')->label(__('admin.fields.status'))->badge(),
                TextEntry::make('period')->label(__('admin.fields.period'))
                    ->state(fn (Settlement $r) => $r->period_from?->toDateString().' → '.$r->period_to?->toDateString()),
            ]),
            Section::make(__('admin.settlements.breakdown'))->columns(5)->columnSpanFull()->schema([
                TextEntry::make('gross_amount')->label(__('admin.fields.gross_amount'))->formatStateUsing($money),
                TextEntry::make('commission_amount')->label(__('admin.fields.commission'))->formatStateUsing($money)->color('danger'),
                TextEntry::make('refunds_amount')->label(__('admin.fields.refunds_amount'))->formatStateUsing($money)->color('danger'),
                TextEntry::make('adjustments_amount')->label(__('admin.fields.adjustments_amount'))->formatStateUsing($money),
                TextEntry::make('net_amount')->label(__('admin.fields.net_amount'))->formatStateUsing($money)->weight('bold')->color('success')->size('lg'),
            ]),
            Section::make(__('admin.tabs.bank'))->columns(3)->schema([
                TextEntry::make('bank_snapshot.bank_name')->label(__('admin.fields.bank_name'))->placeholder('-'),
                TextEntry::make('bank_snapshot.account_holder')->label(__('admin.fields.account_holder'))->placeholder('-'),
                TextEntry::make('bank_snapshot.iban')->label(__('admin.fields.iban'))->placeholder(__('admin.settlements.missing_iban'))
                    ->copyable()->fontFamily('mono'),
            ]),
            Section::make(__('admin.settlements.workflow'))->columns(3)->schema([
                TextEntry::make('creator.name')->label(__('admin.fields.created_by'))->placeholder(__('admin.system')),
                TextEntry::make('created_at')->label(__('admin.fields.created_at'))->dateTime(),
                TextEntry::make('approver.name')->label(__('admin.fields.approved_by'))->placeholder('-')
                    ->helperText(fn (Settlement $r) => $r->approved_at?->toDateTimeString()),
                TextEntry::make('payer.name')->label(__('admin.fields.paid_by'))->placeholder('-')
                    ->helperText(fn (Settlement $r) => $r->paid_at?->toDateTimeString()),
                TextEntry::make('payment_reference')->label(__('admin.fields.payment_reference'))->placeholder('-')->copyable(),
                TextEntry::make('receipt_path')->label(__('admin.fields.receipt'))->placeholder('-')
                    ->formatStateUsing(fn () => __('admin.actions.open_file'))
                    ->url(fn (Settlement $r) => $r->receiptUrl(), true)
                    ->color('primary'),
                TextEntry::make('notes')->label(__('admin.fields.notes'))->placeholder('-')->columnSpanFull(),
            ]),
        ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->modifyQueryUsing(fn (Builder $query) => $query->with(['provider']))
            ->defaultSort('created_at', 'desc')
            ->columns([
                TextColumn::make('number')->label(__('admin.fields.number'))->searchable()->weight('bold'),
                TextColumn::make('provider.name_ar')->formatStateUsing(Fmt::localized('provider.name'))->label(__('admin.fields.provider'))->searchable()->limit(30),
                TextColumn::make('period_to')->label(__('admin.fields.period'))
                    ->formatStateUsing(fn (Settlement $r) => $r->period_from?->toDateString().' → '.$r->period_to?->toDateString()),
                TextColumn::make('gross_amount')->label(__('admin.fields.gross_amount'))->formatStateUsing(fn ($state) => Fmt::sar($state))->toggleable(),
                TextColumn::make('commission_amount')->label(__('admin.fields.commission'))->formatStateUsing(fn ($state) => Fmt::sar($state))->toggleable(),
                TextColumn::make('net_amount')->label(__('admin.fields.net_amount'))->formatStateUsing(fn ($state) => Fmt::sar($state))->weight('bold')
                    ->summarize(Sum::make()->label(__('admin.fields.total'))->formatStateUsing(fn ($state) => Fmt::sar($state))),
                TextColumn::make('status')->label(__('admin.fields.status'))->badge(),
                TextColumn::make('payment_reference')->label(__('admin.fields.payment_reference'))->placeholder('-')->toggleable(isToggledHiddenByDefault: true),
                TextColumn::make('created_at')->label(__('admin.fields.created_at'))->date()->sortable(),
                TextColumn::make('paid_at')->label(__('admin.fields.paid_at'))->date()->placeholder('-')->sortable(),
            ])
            ->filters([
                SelectFilter::make('status')->label(__('admin.fields.status'))->options(SettlementStatus::class),
                SelectFilter::make('provider_id')->label(__('admin.fields.provider'))->relationship('provider', 'name_ar')->getOptionLabelFromRecordUsing(fn ($record) => Fmt::tr($record, 'name'))->searchable(),
                Filter::make('created_at')->columns(2)->columnSpan(2)
                    ->schema([
                        DatePicker::make('from')->label(__('admin.fields.from')),
                        DatePicker::make('to')->label(__('admin.fields.to')),
                    ])
                    ->query(fn (Builder $q, array $data) => $q
                        ->when($data['from'] ?? null, fn ($q, $d) => $q->whereDate('created_at', '>=', $d))
                        ->when($data['to'] ?? null, fn ($q, $d) => $q->whereDate('created_at', '<=', $d))),
            ])
            ->recordActions([ViewAction::make()]);
    }

    public static function getRelations(): array
    {
        return [EntriesRelationManager::class];
    }

    public static function getPages(): array
    {
        return [
            'index' => ListSettlements::route('/'),
            'view' => ViewSettlement::route('/{record}'),
        ];
    }
}
